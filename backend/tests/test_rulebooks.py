class TestPANStructure:
    def test_valid_pan_accepted(self):
        assert is_structurally_valid("PQZPK6899H")

    @pytest.mark.parametrize(
        "value", ["PQZPK6899", "PQZP16899H", "PQZPK689H", "1QZPK6899H"]
    )
    def test_malformed_rejected(self, value):
        assert not is_structurally_valid(value)

    def test_unknown_holder_type_rejected(self):
        """Fourth character encodes the holder category and must be a real one."""
        assert "X" not in HOLDER_TYPES
        assert not is_structurally_valid("PQZXK6899H")


class TestPANSurnameCrossCheck:
    """
    The only redundancy a PAN card carries: the number's fifth character is the
    first letter of the surname, so the number and the printed name must agree.
    """

    def test_matching_surname_initial_passes(self):
        signals = validate_pan(
            None, fields_with(document_number="PQZPK6899H", full_name="PARTH KHODE")
        )
        assert any(s.code == "pan.surname_initial.match" for s in signals)

    def test_mismatched_surname_initial_fails(self):
        signals = validate_pan(
            None, fields_with(document_number="PQZPK6899H", full_name="PARTH SHARMA")
        )
        assert any(s.code == "pan.surname_initial.mismatch" for s in signals)

    def test_mismatch_is_not_reported_as_certain(self):
        """
        Surname-last is a convention, not a rule: mononyms and reordered names
        produce honest mismatches. Strong enough to escalate, not to conclude.
        """
        signals = validate_pan(
            None, fields_with(document_number="PQZPK6899H", full_name="PARTH SHARMA")
        )
        mismatch = next(s for s in signals if s.code == "pan.surname_initial.mismatch")
        assert mismatch.confidence < 0.8

    def test_honorifics_do_not_become_the_surname(self):
        assert surname_initial("SHRI PARTH KHODE") == "K"

    def test_missing_name_is_skip_not_failure(self):
        signals = validate_pan(None, fields_with(document_number="PQZPK6899H"))
        skipped = [s for s in signals if s.code == "pan.surname_initial.no_name"]
        assert skipped and skipped[0].status == SignalStatus.SKIP


class TestPANHonesty:
    def test_check_digit_is_reported_as_unverifiable(self):
        """
        The tenth character IS a check digit, but its algorithm was never
        published. Claiming to have verified it would be inventing evidence.
        """
        signals = validate_pan(None, fields_with(document_number="PQZPK6899H"))
        unverifiable = [s for s in signals if s.code == "pan.check_digit.unverifiable"]
        assert unverifiable and unverifiable[0].status == SignalStatus.SKIP


