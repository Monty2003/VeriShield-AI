"""
Rulebook tests for Aadhaar, PAN and certificates.

No real document data appears here. Aadhaar numbers are generated by computing
a valid Verhoeff check digit over an arbitrary payload, so the tests exercise
real arithmetic without embedding anybody's identity number in source control.
"""

from __future__ import annotations

from datetime import date, timedelta

import pytest

from app.rules.aadhaar import (
    is_valid_aadhaar,
    mask,
    validate_aadhaar,
    verhoeff_check_digit,
    verhoeff_checksum,
)
from app.rules.certificate import (
    find_number_word_phrases,
    validate_certificate,
    words_to_number,
)
from app.rules.pan import (
    HOLDER_TYPES,
    is_structurally_valid,
    surname_initial,
    validate_pan,
)
from app.schemas.document import ExtractedFields, FieldConfidence
from app.schemas.signals import SignalStatus


def make_aadhaar(payload: str = "23412341234") -> str:
    """Build a checksum-valid Aadhaar number from an 11-digit payload."""
    return payload + str(verhoeff_check_digit(payload))


def fields_with(**kwargs) -> ExtractedFields:
    f = ExtractedFields()
    for name, value in kwargs.items():
        setattr(f, name, FieldConfidence(value=value, raw=str(value), confidence=0.9))
    return f


# ---------------------------------------------------------------- Aadhaar --


class TestVerhoeff:
    def test_uidai_published_test_numbers_validate(self):
        for number in ("234123412346", "999999990019"):
            assert verhoeff_checksum(number) == 0

    def test_generated_check_digit_round_trips(self):
        for payload in ("23412341234", "48765432109", "99999999001"):
            assert verhoeff_checksum(make_aadhaar(payload)) == 0

    def test_catches_every_single_digit_error(self):
        """Verhoeff's guarantee, and the reason UIDAI chose it."""
        base = make_aadhaar()
        missed = [
            base[:i] + d + base[i + 1 :]
            for i in range(12)
            for d in "0123456789"
            if d != base[i] and verhoeff_checksum(base[:i] + d + base[i + 1 :]) == 0
        ]
        assert missed == []

    def test_catches_adjacent_transpositions(self):
        """
        The error a plain mod-10 checksum misses entirely, and the one people
        and OCR engines make most: swapping neighbouring digits.
        """
        base = make_aadhaar()
        missed = [
            i
            for i in range(11)
            if base[i] != base[i + 1]
            and verhoeff_checksum(base[:i] + base[i + 1] + base[i] + base[i + 2 :]) == 0
        ]
        assert missed == []

    def test_reserved_leading_digits_rejected(self):
        assert not is_valid_aadhaar("0" + make_aadhaar()[1:])
        assert not is_valid_aadhaar("1" + make_aadhaar()[1:])

    def test_wrong_length_rejected(self):
        assert not is_valid_aadhaar("12345678901")


class TestAadhaarPrivacy:
    def test_mask_reveals_only_last_four(self):
        assert mask("234123412346") == "XXXX XXXX 2346"

    def test_no_signal_ever_contains_the_full_number(self):
        """
        A verification tool must not be the place a national identity number
        leaks from. Reasons and evidence outlive the request in logs and API
        responses.
        """
        number = make_aadhaar()
        for sig in validate_aadhaar(None, fields_with(document_number=number)):
            assert number not in sig.reason
            assert number not in str(sig.evidence)


class TestAadhaarRules:
    def test_valid_number_passes(self):
        signals = validate_aadhaar(None, fields_with(document_number=make_aadhaar()))
        checksum = [s for s in signals if s.code == "aadhaar.checksum.valid"]
        assert checksum and checksum[0].status == SignalStatus.PASS

    def test_invalid_checksum_fails_critically(self):
        bad = make_aadhaar()[:-1] + str((int(make_aadhaar()[-1]) + 1) % 10)
        signals = validate_aadhaar(None, fields_with(document_number=bad))
        failed = [s for s in signals if s.code == "aadhaar.checksum.invalid"]
        assert failed and failed[0].severity.value == "critical"

    def test_reason_names_the_expected_check_digit(self):
        """A reviewer should be able to see the arithmetic, not just the verdict."""
        bad = make_aadhaar()[:-1] + str((int(make_aadhaar()[-1]) + 1) % 10)
        signals = validate_aadhaar(None, fields_with(document_number=bad))
        reason = next(s.reason for s in signals if s.code == "aadhaar.checksum.invalid")
        assert "requires" in reason

    def test_missing_number_blocks_without_accusing(self):
        signals = validate_aadhaar(None, ExtractedFields())
        assert signals[0].status == SignalStatus.ERROR
        assert signals[0].blocking is True

    def test_repeated_digits_flagged(self):
        signals = validate_aadhaar(None, fields_with(document_number="222222222222"))
        assert any(s.code == "aadhaar.number.low_entropy" for s in signals)

    def test_future_date_of_birth_blocks(self):
        tomorrow = date.today() + timedelta(days=1)
        signals = validate_aadhaar(
            None, fields_with(document_number=make_aadhaar(), date_of_birth=tomorrow)
        )
        assert any(s.code == "aadhaar.dob.future" and s.blocking for s in signals)


