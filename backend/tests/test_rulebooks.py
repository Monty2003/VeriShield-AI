class TestNumberWords:
    @pytest.mark.parametrize(
        "phrase,value",
        [
            ("SIXTY THREE", 63),
            ("NINETY", 90),
            ("ONE HUNDRED", 100),
            ("SEVENTEEN", 17),
            ("FOURTY FIVE", 45),  # common print error for 'forty'
        ],
    )
    def test_parsing(self, phrase, value):
        assert words_to_number(phrase) == value

    def test_consecutive_words_group_into_one_number(self):
        found = dict(find_number_word_phrases("TOTAL SIXTY THREE MARKS"))
        assert found.get("SIXTY THREE") == 63


class TestCertificateRules:
    def _marksheet(self, body: str) -> ExtractedFields:
        return fields_with(raw_text=body)

    def test_recognised_board_passes(self):
        signals = validate_certificate(
            None,
            self._marksheet("CENTRAL BOARD OF SECONDARY EDUCATION\nRoll No. 22645310\n2023"),
        )
        assert any(s.code == "certificate.issuer.identified" for s in signals)

    def test_unknown_issuer_blocks(self):
        signals = validate_certificate(None, self._marksheet("SOME RANDOM DOCUMENT\n2023"))
        issuer = next(s for s in signals if s.code == "certificate.issuer.unknown")
        assert issuer.blocking is True

    def test_total_matching_its_words_passes(self):
        signals = validate_certificate(
            None, self._marksheet("CBSE\nENGLISH CORE 301 043 020 063 SIXTY THREE C2")
        )
        assert any(s.code == "certificate.totals.match" for s in signals)

    def test_altered_digits_are_caught_by_the_words(self):
        """
        The forgery this rulebook exists to catch: the mark is raised in
        digits, and the words printed beside it are left behind.
        """
        signals = validate_certificate(
            None, self._marksheet("CBSE\nENGLISH CORE 301 093 020 093 SIXTY THREE C2")
        )
        assert any(s.code == "certificate.totals.mismatch" for s in signals)

    def test_mismatch_is_not_reported_as_certain(self):
        """Dense tables are where OCR makes most of its mistakes."""
        signals = validate_certificate(
            None, self._marksheet("CBSE\nENGLISH CORE 301 093 020 093 SIXTY THREE C2")
        )
        mismatch = next(s for s in signals if s.code == "certificate.totals.mismatch")
        assert mismatch.confidence < 0.8

    def test_future_examination_year_fails(self):
        future = date.today().year + 2
        signals = validate_certificate(None, self._marksheet(f"CBSE\nEXAMINATION {future}"))
        assert any(s.code == "certificate.year.future" for s in signals)

    def test_no_words_present_is_skip_not_pass(self):
        """
        Absence of the cross-check must not read as having passed it.
        """
        signals = validate_certificate(None, self._marksheet("CBSE\nRoll No. 22645310"))
        assert any(
            s.code == "certificate.totals.no_words" and s.status == SignalStatus.SKIP
            for s in signals
        )
